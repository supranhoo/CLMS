// Generates docs/erd/: Mermaid diagrams (one per domain), the data dictionary and the relationship / integrity tables.
//
//   node scripts/erd.mjs            write docs/erd/*.md and docs/erd/*.mmd
//   node scripts/erd.mjs --check    exit 1 if the committed files differ from what the current code would generate
//   node scripts/render-erd.mjs     (optional) render the .mmd files to SVG; needs `npm i --no-save mermaid playwright`
//
// The data comes from the real system: the seed state plus a scenario (scripts/lib/populate.mjs) that creates a record in
// every collection through the API. Nothing here reads a database; the replica has none.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { populate } from './lib/populate.mjs';
import { ENTITIES, GROUPS, RELATIONSHIPS } from './lib/erd-catalogue.mjs';
import { builtInLists, checkIntegrity, coverage, observeColumns, rowsOf } from './lib/erd-model.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'docs/erd');
const check = process.argv.includes('--check');

const p = await populate();
const failedSteps = p.steps.filter(s => s.status >= 400);
if (failedSteps.length) throw new Error('The sample scenario no longer runs: ' + failedSteps.map(s => `${s.name} (${s.status} ${s.message})`).join('; '));
const ctx = { state: p.state, lists: await builtInLists(p.call, p.state) };
await p.close();

const integrity = checkIntegrity(ctx); const cover = coverage(p.state);
if (cover.unclaimed.length) throw new Error('State collections missing from the ERD catalogue: ' + cover.unclaimed.join(', '));
const byId = new Map(ENTITIES.map(e => [e.id, e]));
const observed = new Map(ENTITIES.map(e => [e.id, observeColumns(rowsOf(e, ctx), e.secret)]));
const fkFields = id => new Set(RELATIONSHIPS.filter(r => r.from === id).flatMap(r => r.fields));
const keyFields = id => new Set(byId.get(id).key);
const mType = column => (column?.types?.includes('number') ? 'number' : column?.types?.includes('boolean') ? 'boolean' : column?.types?.some(t => t === 'array' || t === 'object') ? 'json' : 'string');

// ---------------------------------------------------------------- Mermaid, one diagram per domain
function diagram(group) {
  const members = ENTITIES.filter(e => e.group === group);
  const ids = new Set(members.map(e => e.id));
  const rels = RELATIONSHIPS.filter(r => ids.has(r.from) || (ids.has(r.to) && !ids.has(r.from) && false));
  const shown = new Set(ids); for (const r of rels) shown.add(r.to);
  const merged = new Map(); // one line per (parent, child, optional); several fields are joined in the label
  for (const r of rels) { const k = `${r.to}|${r.from}|${r.optional ? 1 : 0}`; const label = (r.label || r.fields.join(' + ')); merged.set(k, { ...r, labels: [...(merged.get(k)?.labels || []), label] }); }
  const lines = ['erDiagram'];
  for (const id of [...shown].sort()) {
    const full = ids.has(id); const columns = observed.get(id); const keys = keyFields(id); const fks = fkFields(id);
    const own = full ? [...keys, ...[...fks].filter(f => !keys.has(f))] : [...keys];
    lines.push(`  ${id} {`);
    for (const field of own) { const tags = [keys.has(field) ? 'PK' : '', full && fks.has(field) ? 'FK' : ''].filter(Boolean).join(','); lines.push(`    ${mType(columns.find(c => c.field === field))} ${field}${tags ? ' ' + tags : ''}`); }
    lines.push('  }');
  }
  for (const r of merged.values()) lines.push(`  ${r.to} ${r.optional ? '|o' : '||'}--o{ ${r.from} : "${[...new Set(r.labels)].join(', ').replace(/"/g, "'")}"`);
  return lines.join('\n') + '\n';
}

// ---------------------------------------------------------------- markdown
const esc = text => String(text ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const stateLocation = e => (e.implicit ? 'built into the server (not in state.json)' : e.reserved ? 'never created' : '`' + e.stateKey + '`');
const enforcedText = { create: 'checked on create', restrict: 'delete / re-key blocked', both: 'checked on create; delete blocked', none: 'not enforced' };

function dictionary() {
  const out = ['# CLMS replica: data dictionary', '', 'Generated by `node scripts/erd.mjs` from the seed state plus a scenario that creates a record in every collection through the API. Types are what was observed, not declared: the replica has no schema. "Filled" is the share of records that have a value.', ''];
  for (const group of Object.keys(GROUPS)) {
    out.push(`## ${GROUPS[group]}`, '');
    for (const e of ENTITIES.filter(x => x.group === group)) {
      const rows = rowsOf(e, ctx); const columns = observed.get(e.id);
      const refs = RELATIONSHIPS.filter(r => r.from === e.id);
      out.push(`### ${e.id}`, '', `${e.note}`, '', `- Stored in: ${stateLocation(e)}`, `- Business key: ${e.key.map(k => '`' + k + '`').join(' + ')}`, `- Records in the sample state: ${rows.length}`, '');
      if (!columns.length) { out.push('_No columns observed (the collection is empty or reserved)._', ''); continue; }
      out.push('| Column | Type | Filled | Key | References | Example |', '| --- | --- | --- | --- | --- | --- |');
      for (const c of columns) {
        const ref = refs.filter(r => r.fields.includes(c.field)).map(r => `${r.to}.${r.toFields[r.fields.indexOf(c.field)]}`).join(', ');
        out.push(`| \`${c.field}\` | ${esc(c.types.join(' / ') || 'null')} | ${c.rows ? Math.round(100 * c.filled / rows.length) : 0}% | ${keyFields(e.id).has(c.field) ? 'PK' : ''} | ${esc(ref)} | ${esc(c.example ?? '')} |`);
      }
      out.push('');
    }
  }
  return out.join('\n');
}

function erdPage(diagrams) {
  const out = [
    '# CLMS replica: entity-relationship model', '',
    '> **What this is.** The *logical* data model of the CLMS **development replica**, derived from the code and checked against live data. It is not the production SQL Server schema: that was never available to this project, and the replica deliberately has none. Its "tables" are collections in `.local-demo/state.json`, its "foreign keys" are business codes that nothing in the storage layer enforces, and several lookup lists are constants inside the server. Use this to understand and test the replica; do not use it to design or migrate the production database.',
    '',
    'Generated by `node scripts/erd.mjs`; `npm test` fails if it drifts (see `tests/erd.test.mjs`). Column-level detail is in [DATA-DICTIONARY.md](DATA-DICTIONARY.md).', '',
    '## How to read the diagrams', '',
    '- `PK` is the business key (a code, not a surrogate id, except where the collection has a counter such as `trans_id`).',
    '- `FK` is a reference by value to another entity\'s key. Each line is *parent → child*; a hollow end (`|o`) means the reference may be empty.',
    '- Entities drawn with only their key are parents shown for context. Built-in lists (legal entity, department, leave type ...) are real entities of the model but live in server code, not in the state file.',
    '- The **Enforcement** column in the relationship table is what the API actually checks today. Most references are *not* enforced; that is the main thing a tester should know about this data.', '',
    '## Overview', '',
  ];
  const sizes = Object.keys(GROUPS).map(g => `${GROUPS[g]}: ${ENTITIES.filter(e => e.group === g).length}`).join('; ');
  out.push(`${ENTITIES.length} entities (${ENTITIES.filter(e => e.implicit).length} built-in lists, ${ENTITIES.filter(e => e.reserved).length} reserved) and ${RELATIONSHIPS.length} references. ${sizes}.`, '');
  out.push('```mermaid', overview(), '```', '', '![Domain overview](erd-overview.svg)', '', '_Overview: entities grouped by domain; arrows run parent → child. Colours are not used._', '');
  for (const group of Object.keys(GROUPS)) out.push(`## ${GROUPS[group]}`, '', '```mermaid', diagrams[group].trim(), '```', '', `![${GROUPS[group]}](erd-${group}.svg)`, '', ...ENTITIES.filter(e => e.group === group).map(e => `- **${e.id}** (${stateLocation(e)}): ${e.note}`), '');

  out.push('## Relationships and how they are enforced', '', '| Child | Column(s) | Parent | Optional | Enforcement | Rows checked | Dangling | Note |', '| --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const r of integrity) out.push(`| ${r.from} | \`${esc(r.label || r.fields.join(' + '))}\` | ${r.to} | ${r.optional ? 'yes' : ''} | ${enforcedText[r.enforced]} | ${r.checked} | ${r.dangling.length ? '**' + r.dangling.length + '**' : '0'} | ${esc(r.note || '')} |`);
  const tally = integrity.reduce((a, r) => (a[r.enforced] = (a[r.enforced] || 0) + 1, a), {});
  out.push('', `Of ${integrity.length} references: ${tally.create || 0} checked on create, ${tally.both || 0} checked on create and protected on delete, ${tally.restrict || 0} protected on delete only, **${tally.none || 0} not enforced at all**.`, '');
  const bad = integrity.filter(r => r.dangling.length);
  out.push('## Integrity of the sample data', '', `Every reference above was checked against the seed plus the scenario state (${integrity.reduce((a, r) => a + r.checked, 0)} values). ` + (bad.length ? `Dangling: ${bad.map(r => `${r.from}.${r.fields.join('+')} → ${r.to} (${r.dangling.join('; ')})`).join('; ')}.` : 'None dangling.'), '',
    '## Things the model does not express', '',
    '- **Dates** are stored as text in two shapes: `YYYY-MM-DD` and full ISO date-times (`2026-09-01T00:00:00.000Z`). Seeded process months use the long form; months added through the API use the short form. Comparisons in the server normalise to the first 10 characters; an exporter or test that compares raw strings must do the same.',
    '- **Duplicate spellings.** Several records carry the same value under two names (`Employee_Code` and `employee_code`, `billingType` and `billingtype`, `dept` and `dept_code`). Both are written by the server; read either, write through the API.',
    '- **Case.** Business keys are case-sensitive text (`D001` is not `d001`). Numeric spreadsheet cells are converted to text on write.',
    '- **Leave across months.** A leave application spanning two months posts all its days to the first month in the ledger.',
    '- **Deleting.** Contractors and workers cannot be deleted through the API (a worker is made inactive; an inactive worker keeps all history). Master rows that are still referenced cannot be deleted or re-keyed (HTTP 409). A process month that has earnings, deductions or arrears cannot be deleted (409). Deleting a leave application also deletes its ledger rows. Every other delete (approved manpower, sandwich rules, service-charge rules, wage locks, muster and regularisation rows, wage inputs) removes the row alone, because nothing depends on it.', '');
  return out.join('\n');
}

function overview() {
  // 47 entities and 66 references do not fit on one readable ER diagram, so the overview is a map of the domains:
  // an arrow runs from the domain that holds the reference to the domain it points at, labelled with how many references.
  const domainOf = new Map(ENTITIES.map(e => [e.id, e.group]));
  const lines = ['flowchart LR'];
  for (const g of Object.keys(GROUPS)) {
    const members = ENTITIES.filter(e => e.group === g); const inside = RELATIONSHIPS.filter(r => domainOf.get(r.from) === g && domainOf.get(r.to) === g).length;
    lines.push(`  ${g}["<b>${GROUPS[g]}</b><br/>${members.length} entities, ${inside} reference${inside === 1 ? "" : "s"} inside"]`);
  }
  const counts = new Map();
  for (const r of RELATIONSHIPS) { const a = domainOf.get(r.from); const b = domainOf.get(r.to); if (a !== b) counts.set(`${a}|${b}`, (counts.get(`${a}|${b}`) || 0) + 1); }
  for (const [key, n] of [...counts].sort()) { const [a, b] = key.split('|'); lines.push(`  ${a} -->|"${n} reference${n > 1 ? 's' : ''}"| ${b}`); }
  return lines.join('\n');
}

// ---------------------------------------------------------------- write (or verify)
const diagrams = Object.fromEntries(Object.keys(GROUPS).map(g => [g, diagram(g)]));
const files = { 'ERD.md': erdPage(diagrams), 'DATA-DICTIONARY.md': dictionary(), 'erd-overview.mmd': overview() + '\n' };
for (const g of Object.keys(GROUPS)) files[`erd-${g}.mmd`] = diagrams[g];
if (check) {
  const stale = Object.entries(files).filter(([name, text]) => !fs.existsSync(path.join(outDir, name)) || fs.readFileSync(path.join(outDir, name), 'utf8') !== text).map(([name]) => name);
  if (stale.length) { console.error('docs/erd is out of date: ' + stale.join(', ') + '. Run `node scripts/erd.mjs`.'); process.exit(1); }
  console.log('docs/erd is up to date.');
} else {
  fs.mkdirSync(outDir, { recursive: true });
  for (const [name, text] of Object.entries(files)) fs.writeFileSync(path.join(outDir, name), text);
  console.log(`Wrote ${Object.keys(files).length} files to docs/erd (${ENTITIES.length} entities, ${RELATIONSHIPS.length} references, ${integrity.filter(r => r.dangling.length).length} with dangling values).`);
}
